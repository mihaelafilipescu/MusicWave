CREATE OR REPLACE PROCEDURE RAPORT_ARTIST_COLECTII(P_ID_ARTIST IN NUMBER) AS
      -- VARRAY: MAXIM 5 PIESE
    TYPE T_VARRAY_PIESE IS VARRAY(5) OF VARCHAR2(100);
    V_PIESE T_VARRAY_PIESE := T_VARRAY_PIESE();
       -- NESTED TABLE: SCORURI RECENZII
    TYPE T_NT_SCORURI IS TABLE OF NUMBER;
    V_SCORURI T_NT_SCORURI;
       -- ASSOCIATIVE ARRAY: GEN -> NUMAR PIESE
    TYPE T_AA_GENURI IS TABLE OF NUMBER INDEX BY VARCHAR2(100);
    V_GENURI_CNT T_AA_GENURI;

    V_NUME_ARTIST  ARTIST.NUME%TYPE;
    V_SUM          NUMBER := 0;
    V_AVG          NUMBER := NULL;

--     V_TITLU PIESA.TITLU%TYPE;
--
--     CURSOR C_PREZENTARE IS
--         SELECT P.TITLU
--         FROM PIESA P
--         WHERE P.ID_ARTIST = P_ID_ARTIST
--         ORDER BY P.DATA_LANSARII DESC NULLS LAST, P.ID_PIESA DESC;

BEGIN
    -- PREIA NUMELE ARTISTULUI
    SELECT NUME
    INTO V_NUME_ARTIST
    FROM ARTIST
    WHERE ID_ARTIST = P_ID_ARTIST;

    DBMS_OUTPUT.PUT_LINE('=== RAPORT ARTIST ===');
    DBMS_OUTPUT.PUT_LINE('ARTIST: ' || V_NUME_ARTIST || ' (ID=' || P_ID_ARTIST || ')');
    DBMS_OUTPUT.PUT_LINE(' ');

    -- VARRAY – ULTIMELE MAXIM 5 PIESE
    FOR R IN (
        SELECT TITLU
        FROM (
            SELECT P.TITLU
            FROM PIESA P
            WHERE P.ID_ARTIST = P_ID_ARTIST
            ORDER BY P.DATA_LANSARII DESC NULLS LAST, P.ID_PIESA DESC
        )
        WHERE ROWNUM <= 5
    ) LOOP
        V_PIESE.EXTEND;
        V_PIESE(V_PIESE.COUNT) := R.TITLU;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('1) ULTIMELE PIESE (MAX 5):');
    IF V_PIESE.COUNT = 0 THEN
        DBMS_OUTPUT.PUT_LINE('   (ARTISTUL NU ARE PIESE)');
    ELSE
        FOR I IN 1 .. V_PIESE.COUNT LOOP
            DBMS_OUTPUT.PUT_LINE('   ' || I || '. ' || V_PIESE(I));
        END LOOP;
    END IF;
    DBMS_OUTPUT.PUT_LINE(' ');

    -- NESTED TABLE – SCORURI RECENZII
    SELECT R.SCOR
    BULK COLLECT INTO V_SCORURI
    FROM RECENZIE R
    JOIN PIESA P ON P.ID_PIESA = R.ID_PIESA
    WHERE P.ID_ARTIST = P_ID_ARTIST;

    DBMS_OUTPUT.PUT_LINE('2) RECENZII:');
    DBMS_OUTPUT.PUT_LINE('   NR. SCORURI: ' || V_SCORURI.COUNT);

    IF V_SCORURI.COUNT = 0 THEN
        DBMS_OUTPUT.PUT_LINE('   MEDIA SCORURILOR: N/A (NU EXISTA RECENZII)');
    ELSE
        V_SUM := 0;
        FOR I IN 1 .. V_SCORURI.COUNT LOOP
            V_SUM := V_SUM + V_SCORURI(I);
        END LOOP;

        V_AVG := V_SUM / V_SCORURI.COUNT;
        DBMS_OUTPUT.PUT_LINE('   MEDIA SCORURILOR: ' || ROUND(V_AVG, 2));
    END IF;
    DBMS_OUTPUT.PUT_LINE(' ');

    -- ASSOCIATIVE ARRAY – NUMAR PIESE PE GEN
    FOR G IN (
        SELECT NVL(GEN.NUME_GEN, 'FARA_GEN') AS NUME_GEN, COUNT(*) AS CNT
        FROM PIESA P
        LEFT JOIN GEN ON GEN.ID_GEN = P.ID_GEN
        WHERE P.ID_ARTIST = P_ID_ARTIST
        GROUP BY NVL(GEN.NUME_GEN, 'FARA_GEN')
    ) LOOP
        V_GENURI_CNT(G.NUME_GEN) := G.CNT;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('3) PIESE PE GEN:');
    DECLARE
        K VARCHAR2(100);
    BEGIN
        K := V_GENURI_CNT.FIRST;
        IF K IS NULL THEN
            DBMS_OUTPUT.PUT_LINE('   (ARTISTUL NU ARE PIESE / GENURI)');
        ELSE
            WHILE K IS NOT NULL LOOP
                DBMS_OUTPUT.PUT_LINE('   ' || K || ' -> ' || V_GENURI_CNT(K));
                K := V_GENURI_CNT.NEXT(K);
            END LOOP;
        END IF;
    END;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('NU EXISTA ARTIST CU ID=' || P_ID_ARTIST);
END;
/

SET SERVEROUTPUT ON
BEGIN
  RAPORT_ARTIST_COLECTII(2);
END;
/
