CREATE OR REPLACE PROCEDURE RAPORT_COMPLET_ARTIST(P_ID_ARTIST IN NUMBER) AS

    --CURSOR 1 (NEPARAMETRIZAT): ALBUMELE ARTISTULUI
    CURSOR C_ALBUME IS
        SELECT ID_ALBUM, TITLU, AN_LANSARE
        FROM ALBUM
        WHERE ID_ARTIST = P_ID_ARTIST
        ORDER BY AN_LANSARE, ID_ALBUM;

    --CURSOR 2 (PARAMETRIZAT): PIESELE DIN ALBUM
    CURSOR C_PIESE_ALBUM(P_ID_ALBUM IN NUMBER) IS
        SELECT P.TITLU, PA.NUMAR_POZITIE
        FROM PIESA_ALBUM PA
        JOIN PIESA P ON P.ID_PIESA = PA.ID_PIESA
        WHERE PA.ID_ALBUM = P_ID_ALBUM
        ORDER BY PA.NUMAR_POZITIE NULLS LAST, P.ID_PIESA;

    --CURSOR PENTRU PIESE INDIVIDUALE (PRIN INREGISTRARE)
    CURSOR C_PIESE_INDIVIDUALE IS
        SELECT DISTINCT P.TITLU
        FROM INREGISTRARE I
        JOIN PIESA P ON P.ID_PIESA = I.ID_PIESA
        JOIN PIESA_INDIVIDUALA PI ON PI.ID_PIESA = P.ID_PIESA
        WHERE I.ID_ARTIST = P_ID_ARTIST
        ORDER BY P.TITLU;

    V_NUME_ARTIST ARTIST.NUME%TYPE;
    V_NR_ALBUME  NUMBER := 0;
    V_NR_PIESE   NUMBER := 0;
    V_NR_SINGLE  NUMBER := 0;

BEGIN
    --NUMELE ARTISTULUI
    SELECT NUME INTO V_NUME_ARTIST
    FROM ARTIST
    WHERE ID_ARTIST = P_ID_ARTIST;

    DBMS_OUTPUT.PUT_LINE('=== RAPORT COMPLET ARTIST ===');
    DBMS_OUTPUT.PUT_LINE('ARTIST: ' || V_NUME_ARTIST || ' (ID=' || P_ID_ARTIST || ')');
    DBMS_OUTPUT.PUT_LINE(' ');

    -- ALBUME + PIESE DIN ALBUME
    DBMS_OUTPUT.PUT_LINE('--- ALBUME SI PIESE DIN ALBUME ---');

    FOR A IN C_ALBUME LOOP
        V_NR_ALBUME := V_NR_ALBUME + 1;

        DBMS_OUTPUT.PUT_LINE(
            'ALBUM: ' || A.TITLU ||
            ' (ID_ALBUM=' || A.ID_ALBUM ||
            ', AN=' || A.AN_LANSARE || ')'
        );

        V_NR_PIESE := 0;

        FOR P_REC IN C_PIESE_ALBUM(A.ID_ALBUM) LOOP
            V_NR_PIESE := V_NR_PIESE + 1;

            IF P_REC.NUMAR_POZITIE IS NOT NULL THEN
                DBMS_OUTPUT.PUT_LINE('   ' || P_REC.NUMAR_POZITIE || '. ' || P_REC.TITLU);
            ELSE
                DBMS_OUTPUT.PUT_LINE('   - ' || P_REC.TITLU);
            END IF;
        END LOOP;

        IF V_NR_PIESE = 0 THEN
            DBMS_OUTPUT.PUT_LINE('   (NU EXISTA PIESE IN ACEST ALBUM)');
        END IF;

        DBMS_OUTPUT.PUT_LINE(' ');
    END LOOP;

    IF V_NR_ALBUME = 0 THEN
        DBMS_OUTPUT.PUT_LINE('(ARTISTUL NU ARE ALBUME)');
        DBMS_OUTPUT.PUT_LINE(' ');
    END IF;

    --PIESE INDIVIDUALE
    DBMS_OUTPUT.PUT_LINE('--- PIESE INDIVIDUALE (SINGLE-URI) ---');

    FOR S IN C_PIESE_INDIVIDUALE LOOP
        V_NR_SINGLE := V_NR_SINGLE + 1;
        DBMS_OUTPUT.PUT_LINE('   - ' || S.TITLU);
    END LOOP;

    IF V_NR_SINGLE = 0 THEN
        DBMS_OUTPUT.PUT_LINE('   (ARTISTUL NU ARE PIESE INDIVIDUALE)');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('NU EXISTA ARTIST CU ID=' || P_ID_ARTIST);
END;
/

SET SERVEROUTPUT ON
BEGIN
    RAPORT_COMPLET_ARTIST(5);
END;