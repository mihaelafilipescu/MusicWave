CREATE OR REPLACE PROCEDURE VERIFICA_SINGLE_ARTIST_PROD(
    P_ID_ARTIST     IN NUMBER,
    P_ID_PRODUCATOR IN NUMBER
) AS
    E_ARTIST_INEXISTENT     EXCEPTION;
    E_PRODUCATOR_INEXISTENT EXCEPTION;
    E_FARA_SINGLEURI        EXCEPTION;

    V_NUME_ARTIST ARTIST.NUME%TYPE;
    V_NUME_PROD   PRODUCATOR.NUME%TYPE;
    V_NR_SINGLE   NUMBER;
    V_COUNT       NUMBER;

BEGIN
    -- O SINGURA COMANDA SQL CU 5 TABELE
    SELECT A.NUME, PR.NUME, COUNT(DISTINCT PI.ID_PIESA)
    INTO V_NUME_ARTIST, V_NUME_PROD, V_NR_SINGLE
    FROM ARTIST A                              -- Tabela 1
    CROSS JOIN PRODUCATOR PR                   -- Tabela 2
    LEFT JOIN INREGISTRARE I                   -- Tabela 3
        ON I.ID_ARTIST = A.ID_ARTIST
    LEFT JOIN PIESA P                          -- Tabela 4
        ON P.ID_PIESA = I.ID_PIESA
    LEFT JOIN PIESA_INDIVIDUALA PI             -- Tabela 5
        ON PI.ID_PIESA = P.ID_PIESA
        AND PI.ID_PRODUCATOR = PR.ID_PRODUCATOR
    WHERE A.ID_ARTIST = P_ID_ARTIST
      AND PR.ID_PRODUCATOR = P_ID_PRODUCATOR
    GROUP BY A.NUME, PR.NUME;

    -- Verificare daca exista single-uri
    IF V_NR_SINGLE = 0 THEN
        RAISE E_FARA_SINGLEURI;
    END IF;

    -- CAZ OK
    DBMS_OUTPUT.PUT_LINE('EXISTA SINGLE-URI PENTRU ACEASTA PERECHE DE ARTIST SI PRODUCATOR.');
    DBMS_OUTPUT.PUT_LINE('ARTIST: ' || V_NUME_ARTIST || ' (ID=' || P_ID_ARTIST || ')');
    DBMS_OUTPUT.PUT_LINE('PRODUCATOR: ' || V_NUME_PROD || ' (ID=' || P_ID_PRODUCATOR || ')');
    DBMS_OUTPUT.PUT_LINE('NUMAR SINGLE-URI: ' || V_NR_SINGLE);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        -- Trebuie sa verificam CARE lipseste
        SELECT COUNT(*) INTO V_COUNT
        FROM ARTIST
        WHERE ID_ARTIST = P_ID_ARTIST;

        IF V_COUNT = 0 THEN
            RAISE E_ARTIST_INEXISTENT;
        END IF;

        SELECT COUNT(*) INTO V_COUNT
        FROM PRODUCATOR
        WHERE ID_PRODUCATOR = P_ID_PRODUCATOR;

        IF V_COUNT = 0 THEN
            RAISE E_PRODUCATOR_INEXISTENT;
        END IF;

    WHEN E_ARTIST_INEXISTENT THEN
        DBMS_OUTPUT.PUT_LINE('EROARE: ARTISTUL CU ID=' || P_ID_ARTIST || ' NU EXISTA.');

    WHEN E_PRODUCATOR_INEXISTENT THEN
        DBMS_OUTPUT.PUT_LINE('EROARE: PRODUCATORUL CU ID=' || P_ID_PRODUCATOR || ' NU EXISTA.');

    WHEN E_FARA_SINGLEURI THEN
        DBMS_OUTPUT.PUT_LINE('INFO: NU EXISTA SINGLE-URI PENTRU ARTISTUL ' || V_NUME_ARTIST ||
                             ' CU PRODUCATORUL ' || V_NUME_PROD || '.');
END;
/

SET SERVEROUTPUT ON
BEGIN
  VERIFICA_SINGLE_ARTIST_PROD(2, 3);
END;
/

BEGIN
  VERIFICA_SINGLE_ARTIST_PROD(2, 5);
END;
/

BEGIN
  VERIFICA_SINGLE_ARTIST_PROD(99999, 3);
END;
/

BEGIN
  VERIFICA_SINGLE_ARTIST_PROD(2, 99999);
END;
/
