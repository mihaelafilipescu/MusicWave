CREATE OR REPLACE FUNCTION PIESA_UNICA_ARTIST(P_ID_ARTIST IN NUMBER)
RETURN VARCHAR2
IS
    V_TITLU_PIESA PIESA.TITLU%TYPE;
    V_NUME_ARTIST ARTIST.NUME%TYPE;
BEGIN
    --O SINGURA COMANDA SQL CU 3 TABELE
    SELECT
        P.TITLU, A.NUME
    INTO V_TITLU_PIESA, V_NUME_ARTIST
    FROM ARTIST A
    JOIN INREGISTRARE I ON I.ID_ARTIST = A.ID_ARTIST
    JOIN PIESA P ON P.ID_PIESA = I.ID_PIESA
    WHERE A.ID_ARTIST = P_ID_ARTIST;

    RETURN V_NUME_ARTIST || ': ' || V_TITLU_PIESA;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'ARTISTUL NU ARE NICIO PIESA';

    WHEN TOO_MANY_ROWS THEN
        RETURN 'ARTISTUL ARE MAI MULTE PIESE';

END;
/

SELECT PIESA_UNICA_ARTIST(1) AS REZULTAT FROM DUAL;

SELECT PIESA_UNICA_ARTIST(99) AS REZULTAT FROM DUAL;

SELECT PIESA_UNICA_ARTIST(2) AS REZULTAT FROM DUAL;

