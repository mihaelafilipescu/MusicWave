--TRIGGER LMD LA NIVEL DE COMANDA
CREATE OR REPLACE TRIGGER TRG_RESTRICT_PIESA_ORE
BEFORE INSERT OR UPDATE OR DELETE ON PIESA
DECLARE
  V_ZI  VARCHAR2(10);
  V_ORA NUMBER;
BEGIN
  V_ZI := TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');
  V_ORA := TO_NUMBER(TO_CHAR(SYSDATE, 'HH24'));

  IF V_ZI IN ('SAT', 'SUN') THEN
    RAISE_APPLICATION_ERROR(-20010, 'OPERATIILE PE PIESA SUNT INTERZISE IN WEEKEND.');
  END IF;

  IF INSERTING THEN
    IF NOT (V_ORA >= 0 AND V_ORA < 23) THEN
      RAISE_APPLICATION_ERROR(-20011, 'INSERT PE PIESA PERMIS DOAR INTRE 00:00-23:00 (LUNI-VINERI).');
    END IF;

  ELSIF UPDATING THEN
    IF NOT (V_ORA >= 10 AND V_ORA < 20) THEN
      RAISE_APPLICATION_ERROR(-20012, 'UPDATE PE PIESA PERMIS DOAR INTRE 10:00-20:00 (LUNI-VINERI).');
    END IF;

  ELSIF DELETING THEN
    IF NOT (V_ORA >= 20 AND V_ORA <= 23) THEN
      RAISE_APPLICATION_ERROR(-20013, 'DELETE PE PIESA PERMIS DOAR INTRE 20:00-23:00 (LUNI-VINERI).');
    END IF;
  END IF;

END;
/




