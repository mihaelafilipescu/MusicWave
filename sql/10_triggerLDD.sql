--CREAREA UNUI TABEL DE LOG
CREATE TABLE LOG_LDD (
    TIP_OPERATIE VARCHAR2(50),
    TIP_OBIECT   VARCHAR2(50),
    NUME_OBIECT  VARCHAR2(50),
    UTILIZ       VARCHAR2(30),
    DATA_OP      TIMESTAMP
);
/

--TRIGGERUL
CREATE OR REPLACE TRIGGER TRIGGER_LDD
AFTER CREATE OR ALTER OR DROP ON SCHEMA
DECLARE
    V_USER    VARCHAR2(30);
    V_DATA_OP TIMESTAMP;
BEGIN
    SELECT USER INTO V_USER FROM DUAL;
    SELECT SYSTIMESTAMP INTO V_DATA_OP FROM DUAL;

    INSERT INTO LOG_LDD (
        TIP_OPERATIE,
        NUME_OBIECT,
        TIP_OBIECT,
        UTILIZ,
        DATA_OP
    )
    VALUES (
        ORA_SYSEVENT,
        ORA_DICT_OBJ_NAME,
        ORA_DICT_OBJ_TYPE,
        V_USER,
        V_DATA_OP
    );
END;
/

