-- TABEL DE LOG PT TABELA ALBUM
CREATE TABLE LOG_LMD_ALBUM (
    ID_LOG        NUMBER PRIMARY KEY,
    OPERATIE      VARCHAR2(10),
    ID_ALBUM      NUMBER,
    TITLU_OLD     VARCHAR2(100),
    TITLU_NEW     VARCHAR2(100),
    PRET_OLD      NUMBER,
    PRET_NEW      NUMBER,
    UTILIZATOR    VARCHAR2(30),
    DATA_MODIF    TIMESTAMP
);

DROP SEQUENCE SEQ_LOG_LMD_ALBUM;

CREATE SEQUENCE SEQ_LOG_LMD_ALBUM
START WITH 1
INCREMENT BY 1;

-- TRIGGERUL
CREATE OR REPLACE TRIGGER TRG_LMD_ALBUM
AFTER INSERT OR UPDATE OR DELETE ON ALBUM
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO LOG_LMD_ALBUM
        VALUES (
            SEQ_LOG_LMD_ALBUM.NEXTVAL,
            'INSERT',
            :NEW.ID_ALBUM,
            NULL, :NEW.TITLU,
            NULL, :NEW.PRET,
            USER,
            SYSTIMESTAMP
        );

    ELSIF UPDATING THEN
        INSERT INTO LOG_LMD_ALBUM
        VALUES (
            SEQ_LOG_LMD_ALBUM.NEXTVAL,
            'UPDATE',
            :NEW.ID_ALBUM,
            :OLD.TITLU, :NEW.TITLU,
            :OLD.PRET,  :NEW.PRET,
            USER,
            SYSTIMESTAMP
        );

    ELSIF DELETING THEN
        INSERT INTO LOG_LMD_ALBUM
        VALUES (
            SEQ_LOG_LMD_ALBUM.NEXTVAL,
            'DELETE',
            :OLD.ID_ALBUM,
            :OLD.TITLU, NULL,
            :OLD.PRET,  NULL,
            USER,
            SYSTIMESTAMP
        );
    END IF;
END;
